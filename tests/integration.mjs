// Run against a disposable LOCAL preview database only. Creates test households.
import assert from 'node:assert/strict';
const base=process.env.HEARTH_TEST_URL||'http://127.0.0.1:8787';
if(!['localhost','127.0.0.1'].includes(new URL(base).hostname))throw Error('Tests require a local disposable database.');
const endpoint=base+'/api/household';let checks=0;
async function call(body,cookie='',expected=200,origin=base){const r=await fetch(endpoint,{method:'POST',headers:{'content-type':'application/json',origin,cookie},body:JSON.stringify(body)});const d=await r.json();assert.equal(r.status,expected,JSON.stringify(d));checks++;return {d,cookie:r.headers.get('set-cookie')?.split(';')[0]||cookie};}
async function get(cookie,month='2026-10',expected=200){const r=await fetch(endpoint+'?month='+month,{headers:{cookie}});assert.equal(r.status,expected);checks++;return r.json();}
const suffix=crypto.randomUUID().slice(0,8),password='Local-test-only-pass-8192';
const register=slug=>({action:'register',familyName:slug,slug:slug+'-'+suffix,size:3,currency:'EUR',name:'Test Admin',username:'admin',password});
await get('',undefined,401);
const a=await call(register('test-alpha')),b=await call(register('test-beta'));
await call({action:'login',slug:'test-alpha-'+suffix,username:'admin',password:'wrong'},'',401);
const login=await call({action:'login',slug:'test-alpha-'+suffix,username:'admin',password});assert.ok(login.cookie.includes('hearth_session='));checks++;
await call({action:'expense',amount:12345,description:'Alpha groceries',category:'Groceries',date:'2026-10-04'},a.cookie);
await call({action:'expense',amount:2222,description:'Previous month',category:'Other',date:'2026-09-04'},a.cookie);
const ad=await get(a.cookie),bd=await get(b.cookie);assert.equal(ad.expenses.length,1);assert.equal(ad.previousTotal,2222);assert.equal(bd.expenses.length,0);assert.notEqual(ad.family.slug,bd.family.slug);checks+=4;
const eid=ad.expenses[0].id;
await call({action:'expense',id:eid,amount:1,description:'Attack',category:'Other',date:'2026-10-01'},b.cookie,404);
await call({action:'deleteExpense',id:eid},b.cookie,404);
await call({action:'expense',amount:-1,description:'Invalid amount',category:'Other',date:'2026-10-01'},a.cookie,400);
await call({action:'expense',amount:100,description:'Invalid date',category:'Other',date:'2026-02-31'},a.cookie,400);
await call({action:'settings',name:'Unauthorized',size:2,budget:100},a.cookie,403,'https://evil.invalid');
const invitation=await call({action:'invite'},a.cookie);
const member=await call({action:'join',token:invitation.d.token,name:'Test Member',username:'member',password});
await call({action:'join',token:invitation.d.token,name:'Second Member',username:'second',password},'',400);
await call({action:'invite'},member.cookie,403);
await call({action:'settings',name:'Not admin',size:3,budget:10000},member.cookie,403);
await call({action:'deleteExpense',id:eid},member.cookie,404);
await call({action:'expense',amount:200,description:'Member expense',category:'Food & coffee',date:'2026-10-10'},member.cookie);
const md=await get(member.cookie);assert.equal(md.expenses.length,2);assert.equal(md.members.length,2);checks+=2;
await call({action:'goal',name:'Alpha holiday',target:20000},a.cookie);const goal=(await get(a.cookie)).goals[0];
await call({action:'contribute',id:goal.id,amount:100},b.cookie,404);
await call({action:'contribute',id:goal.id,amount:100},member.cookie);
await call({action:'settings',name:'Test Alpha Updated',size:4,budget:100000},a.cookie);
const updated=await get(a.cookie);assert.equal(updated.family.budget,100000);assert.equal(updated.goals[0].saved,100);checks+=2;
await call({action:'password',currentPassword:password,password:password+'x'},member.cookie);
await get(member.cookie,undefined,401);
await call({action:'login',slug:'test-alpha-'+suffix,username:'member',password:password+'x'});
await call({action:'deleteExpense',id:eid},a.cookie);
const key=crypto.randomUUID();
const pending={action:'expense',clientId:key,expectedMember:ad.user.id,amount:899,description:'Saved on a train',category:'Transport',date:'2026-10-25'};
await Promise.all([call(pending,a.cookie),call(pending,a.cookie)]);
assert.equal((await get(a.cookie)).expenses.filter(e=>e.id===key).length,1);checks++;
await call({...pending,amount:900},a.cookie,409);
await call(pending,b.cookie,403);
const recovery=await call({action:'recoveryCode',password},a.cookie);assert.equal(recovery.d.code.length,64);checks++;
await call({action:'recover',slug:'test-alpha-'+suffix,username:'admin',code:'a'.repeat(64),password:password+'z'},'',401);
const recoveryRequest={action:'recover',slug:'test-alpha-'+suffix,username:'admin',code:recovery.d.code,password:password+'z'};
await call(recoveryRequest);
await get(a.cookie,undefined,401);
await call(recoveryRequest,'',401);
const recovered=await call({action:'login',slug:'test-alpha-'+suffix,username:'admin',password:password+'z'});
const backupResponse=await fetch(endpoint+'?format=backup',{headers:{cookie:recovered.cookie}});const backup=await backupResponse.json();
assert.equal(backupResponse.status,200);assert.equal(backup.family.slug,'test-alpha-'+suffix);assert.ok(backup.expenses.some(e=>e.date.startsWith('2026-09')));assert.ok(backup.members.every(m=>!('password'in m)&&!('recovery'in m)&&!('salt'in m)));checks+=4;
a.cookie=recovered.cookie;
await call({action:'logout'},a.cookie);await get(a.cookie,undefined,401);
const isolated=await get(b.cookie);assert.equal(isolated.expenses.length,0);assert.equal(isolated.goals.length,0);checks+=2;
console.log(`PASS: ${checks} checks — registration, login, invitations, roles, cross-family isolation, amounts, dates, CSRF, monthly totals, savings, password rotation, one-time recovery, idempotent retries, all-month export and logout.`);
