// Some phone browser engines omit Albanian locale data. Keep Albanian dates
// and European number separators consistent even on those devices.
export function numberLocale(locale:string){return locale==='sq-AL'?'de-DE':locale;}
export function calendarDate(date:Date,locale:string,options:Intl.DateTimeFormatOptions):string {
 if(locale!=='sq-AL')return date.toLocaleDateString(locale,options);
 const months=['janar','shkurt','mars','prill','maj','qershor','korrik','gusht','shtator','tetor','nëntor','dhjetor'];
 const short=['jan','shk','mar','pri','maj','qer','kor','gsh','sht','tet','nën','dhj'];
 const parts:string[]=[];
 if(options.day)parts.push(String(date.getDate()));
 if(options.month)parts.push((options.month==='short'?short:months)[date.getMonth()]);
 if(options.year)parts.push(String(date.getFullYear()));
 return parts.join(' ');
}
