/** Translate interface copy only. Member names, notes and identifiers stay untouched. */
export function translate(language:Language,text:string):string {
 if(language==='en'||!text)return text;
 const key=text.trim();let result=albanian[key];
 if(result===undefined){
  let match=key.match(/^(\d+) expenses? · (.+) total$/);
  if(match)result=`${match[1]} ${match[1]==='1'?'shpenzim':'shpenzime'} · gjithsej ${match[2]}`;
  match=key.match(/^(\d+) expenses? waiting to sync$/);
  if(match)result=match[1]==='1'?'1 shpenzim në pritje të sinkronizimit':`${match[1]} shpenzime në pritje të sinkronizimit`;
  match=key.match(/^(.+) is your biggest chapter this month\.$/);
  if(match)result=`${translate(language,match[1])} është kategoria me më shumë shpenzime këtë muaj.`;
  match=key.match(/^(.+) must be (\d+)–(\d+) characters\.$/);
  if(match)result=`${translate(language,match[1])}: përdorni ${match[2]}–${match[3]} karaktere.`;
 }
 if(result===undefined)return text;
 return text.slice(0,text.indexOf(key))+result+text.slice(text.indexOf(key)+key.length);
}
